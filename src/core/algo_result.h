// =============================================================================
// src/core/algo_result.h
//
// 所有算法共用的"返回值格式"。
//
// 设计意图（回答"以后加算法好加吗"）：
//   每个算法都返回同一个 AlgoResult，主程序和菜单就不需要知道每个算法的细节，
//   只需要统一地：拿到云 → 打印摘要 → 保存文件。
//   新增算法时不用改动任何已有代码，只要按这个格式返回即可。
//
// 但这里绝不试图"包住一切"：
//   - 有的算法（KD-Tree 搜索）根本不输出点云，只用 metrics 和 summary；
//   - 有的算法（配准）需要两个输入，那就不走这个统一格式，单独一个接口。
//   强行统一所有签名反而会绑死架构，见 docs/02 的"什么时候必须动公共代码"。
// =============================================================================
#pragma once

#include "core/types.h"

#include <map>
#include <string>

namespace pcp
{

struct AlgoResult
{
    // 主结果点云（滤波后的点、平面内点、聚类中心点……）。
    // 可以为空：表示这个算法不输出点云（例如 KD-Tree 搜索只打印）。
    CloudPtr cloud;

    // "剩余点"。只有分割类算法用得上：RANSAC 分出平面后剩下的点。
    CloudPtr rest;

    // 一行人类可读的摘要，直接打印到控制台。
    std::string summary;

    // 任意数量的数值指标，键是名字、值是数字。
    // 例如 metrics["inliers"] = 1234; metrics["rmse"] = 0.08;
    // 用 map 而不是给每个算法定义一堆字段，是为了新增算法时不用改这个结构体。
    std::map<std::string, double> metrics;

    // 实际写出的文件路径（相对项目根目录），用于打印。没有输出就是空串。
    std::string output_path;
};

}  // namespace pcp
